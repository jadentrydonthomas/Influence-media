import { chromium } from 'playwright';
import path from 'path'; import { fileURLToPath } from 'url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const FIX = path.join(root,'fixtures');
const b = await chromium.launch({executablePath:'/opt/pw-browsers/chromium-1194/chrome-linux/chrome'});
const p = await b.newPage({viewport:{width:1512,height:950}});
await p.goto('file://'+path.join(root,'app','quote-conversion-atlas-shareable.html'));
await p.click('[data-screen="data"]');
await p.setInputFiles('#quoteFiles',['Week 1 - 2026.xlsm','Week 2 - 2026.xlsm','Week 3 - 2026.xlsm'].map(f=>path.join(FIX,f)));
await p.setInputFiles('#orderFiles',[path.join(FIX,'OrderLog_1-10.xlsx')]);
await p.click('#runDashboard');
await p.waitForFunction(()=>/refreshed/i.test(document.getElementById('runStatusTitle').textContent),null,{timeout:90000});
await p.waitForTimeout(1500);
await p.evaluate(()=>window.scrollTo(0,1500));
await p.waitForTimeout(500);
await p.screenshot({path:path.join(root,'test','scrolled-overview.png')});
const railOK = await p.evaluate(()=>{const r=document.querySelector('.rail').getBoundingClientRect();return {top:Math.round(r.top),height:Math.round(r.height)};});
console.log('rail while scrolled:', JSON.stringify(railOK));
// where is the analysis panel relative to the top lens strip?
await p.evaluate(()=>window.scrollTo(0,0));
await p.waitForTimeout(300);
const geom = await p.evaluate(()=>{
  const top=document.querySelector('.comparison-switch [data-analysis]');
  const panel=document.querySelector('.analysis-panel');
  return {topStripY:Math.round(top.getBoundingClientRect().top), panelY:Math.round(panel.getBoundingClientRect().top), viewport:window.innerHeight};
});
console.log('lens strip vs analysis panel:', JSON.stringify(geom));
await p.click('[data-screen="quotes"]');
await p.waitForTimeout(800);
await p.screenshot({path:path.join(root,'test','quotes-top.png')});
const q = await p.evaluate(()=>({rows:document.querySelectorAll('#quoteRows > *').length, h:document.querySelector('#quoteRows').scrollHeight}));
console.log('quote rows:', JSON.stringify(q));
await b.close();
